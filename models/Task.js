const mongoose = require('mongoose');

const STATUSES = ['pending', 'in-progress', 'completed'];
const PRIORITIES = ['low', 'medium', 'high'];
const TRASH_RETENTION_DAYS = 30;
const MAX_ATTACHMENTS = 10;
// Always offered in the category picker and can't be deleted
const DEFAULT_CATEGORIES = ['Bills', 'Family', 'Groceries', 'Health', 'Interview', 'Personal', 'Purchase', 'Study', 'Work'];
const MAX_ATTACHMENT_BYTES = 10 * 1024 * 1024;

const attachmentSchema = new mongoose.Schema(
  {
    originalName: { type: String, required: true, maxlength: 255 },
    storedName: { type: String, required: true }, // random name on disk, never shown to clients
    mimeType: { type: String, default: 'application/octet-stream' },
    size: { type: Number, required: true },
    uploadedAt: { type: Date, default: Date.now },
  },
  {
    toJSON: {
      transform: (doc, ret) => {
        delete ret.storedName;
        return ret;
      },
    },
  }
);

const taskSchema = new mongoose.Schema(
  {
    userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    title: { type: String, required: [true, 'Title is required'], trim: true, maxlength: 200 },
    description: { type: String, trim: true, maxlength: 5000, default: '' },
    status: { type: String, enum: STATUSES, default: 'pending' },
    priority: { type: String, enum: PRIORITIES, default: 'medium' },
    dueDate: { type: Date, default: null },
    category: { type: String, trim: true, maxlength: 50, default: '' },
    attachments: { type: [attachmentSchema], default: [] },
    // Set by the server when the task is marked completed; cleared if it's reopened
    completedAt: { type: Date, default: null },
    // Set when a task is moved to the trash; null for active tasks
    deletedAt: { type: Date, default: null },
  },
  // createdAt / updatedAt are generated by the server, never by the client clock
  { timestamps: true }
);

taskSchema.pre('save', function trackCompletion() {
  if (this.isNew || this.isModified('status')) {
    if (this.status === 'completed') this.completedAt ||= new Date();
    else this.completedAt = null;
  }
});

taskSchema.index({ userId: 1, createdAt: -1 });
// MongoDB permanently removes trashed tasks 30 days after deletion (ignored while deletedAt is null)
taskSchema.index({ deletedAt: 1 }, { expireAfterSeconds: TRASH_RETENTION_DAYS * 24 * 60 * 60 });

module.exports = mongoose.model('Task', taskSchema);
module.exports.STATUSES = STATUSES;
module.exports.PRIORITIES = PRIORITIES;
module.exports.TRASH_RETENTION_DAYS = TRASH_RETENTION_DAYS;
module.exports.MAX_ATTACHMENTS = MAX_ATTACHMENTS;
module.exports.DEFAULT_CATEGORIES = DEFAULT_CATEGORIES;
module.exports.MAX_ATTACHMENT_BYTES = MAX_ATTACHMENT_BYTES;
